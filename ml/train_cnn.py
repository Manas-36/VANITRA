"""Train the Vanitra temporal CNN (model v2) and export it to the glove firmware.

    python ml/train_cnn.py                 # real data from ml/data/
    python ml/train_cnn.py --synthetic     # pipeline test with ml/data_synthetic/ (make_synthetic_data.py)
    python ml/train_cnn.py --by-user       # leave-one-person-out: the honest "new user" number
    python ml/train_cnn.py --folds 0       # skip cross-validation, just train + export

Writes
    firmware/glove_unit/model_cnn.h            weights + labels for the ESP32-S3 (cnn.h runs it)
    firmware/tests/host/test_vectors_cnn.h     frames + expected outputs for the PC parity test
    ml/models/vanitra_cnn.npz                  same weights for ml/live_decoder.py
    ml/reports/cnn_report.md, cnn_confusion.png
        cross-validated accuracy of the CNN next to the v1 MLP on the SAME folds,
        on clean windows and on 'drifted' windows (glove re-worn, no recalibration)

Needs only numpy + scikit-learn (+ matplotlib for the plot). No GPU, no PyTorch.
"""
import argparse
import datetime
import os
import sys
import time

import numpy as np
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix
from sklearn.model_selection import GroupKFold

import vanitra_cnn as vc
from train import ROOT, HERE, REPORTS, c_array, load_takes, load_vocab, fit as fit_mlp
from vanitra_features import compute_features

MODEL_H = os.path.join(ROOT, "firmware", "glove_unit", "model_cnn.h")
VECTORS_H = os.path.join(ROOT, "firmware", "tests", "host", "test_vectors_cnn.h")
NPZ = os.path.join(HERE, "models", "vanitra_cnn.npz")


# ----------------------------------------------------------------------------- training
def train_cnn(takes, y_take, n_out, epochs=40, seed=0, verbose=False):
    rng = np.random.default_rng(seed)
    frames = [t[3] for t in takes]
    allf = np.concatenate(frames)
    mean, std = allf.mean(axis=0), allf.std(axis=0)
    std[std < 1e-3] = 1.0
    counts = np.bincount(y_take, minlength=n_out).astype(float)
    class_w = np.where(counts > 0, counts.sum() / np.maximum(counts, 1) / n_out, 0.0)
    class_w = np.clip(class_w, 0.3, 3.0)
    per_take = [max(1, (len(f) - vc.SEQ_LEN) // 5 + 1) for f in frames]
    p = vc.init_params(n_out, seed, n_in=allf.shape[1])
    opt = vc.Adam(p, lr=2e-3)
    batch = 64
    for ep in range(epochs):
        opt.lr = 2e-3 * 0.5 * (1 + np.cos(np.pi * ep / epochs)) + 1e-4        # cosine decay
        idx = np.repeat(np.arange(len(frames)), per_take)
        rng.shuffle(idx)
        tot = 0.0
        for b in range(0, len(idx), batch):
            ids = idx[b:b + batch]
            x = np.stack([vc.augment_window(frames[i], rng) for i in ids])
            y = y_take[ids]
            probs, cache = vc.forward(p, mean, std, x, train=True, drop=0.2, rng=rng)
            loss, g = vc.backward(p, cache, probs, y, n_out, class_w=class_w)
            opt.step(p, g)
            tot += loss * len(ids)
        if verbose and (ep % 5 == 4 or ep == epochs - 1):
            print(f"  epoch {ep+1:3d}/{epochs}  loss {tot/len(idx):.3f}")
    return p, mean, std


def eval_windows(takes, ids, label_index, stride=5):
    """Windows for both models from the same takes. The MLP sees the LAST 25 frames of each CNN window,
    i.e. exactly what each model would see at the same moment on the glove."""
    xs, fs, ys, gs = [], [], [], []
    for i in ids:
        label, _user, _p, frames = takes[i]
        w = vc.windows(frames, stride)
        if not len(w):
            continue
        xs.append(w)
        ys.append(np.full(len(w), label_index[label]))
        gs.append(np.full(len(w), i))
    if not xs:
        return None
    X = np.concatenate(xs)
    F = np.stack([compute_features(w[-25:]) for w in X])
    return X, F, np.concatenate(ys), np.concatenate(gs)


# ----------------------------------------------------------------------------- export
def export(p, mean, std, model_labels, vocab, info, placeholder):
    vocab_labels = [v[0] for v in vocab]
    say = dict(vocab)
    esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
    rest = model_labels.index("REST") if "REST" in model_labels else -1
    out = ["// AUTO-GENERATED by ml/train_cnn.py — do not edit by hand.", f"// {info}"]
    if placeholder:
        out += ["// *** PLACEHOLDER MODEL: trained on SYNTHETIC data (ml/make_synthetic_data.py). ***",
                "// *** It only proves the pipeline. Record real takes and run: python ml/train_cnn.py ***"]
    n_ch = len(mean)
    out += ["#pragma once",
            f"#define VC_SEQ_LEN {vc.SEQ_LEN}",
            f"#define VC_N_CH {n_ch}          // 15 = right glove only, 30 = right + left glove"]
    for i, (k, cout, pool) in enumerate(vc.LAYERS, 1):
        out += [f"#define VC_K{i} {k}", f"#define VC_C{i} {cout}", f"#define VC_POOL{i} {1 if pool else 0}"]
    n_out = p["bd"].shape[0]
    out += [f"#define VC_N_OUT {n_out}", f"#define VC_REST_INDEX {rest}",
            f'#define VC_INFO "{esc(info)}"', f"#define VC_PLACEHOLDER {1 if placeholder else 0}",
            "// channel order: " + ", ".join(vc.CHANNELS_2[:n_ch]),
            "// conv weights: W[(j*Cin + c)*Cout + o]  (tap j, input channel c, output o); dense: W[i*N_OUT + k]",
            c_array("VC_MEAN", mean), c_array("VC_STD", std)]
    for i in range(1, len(vc.LAYERS) + 1):
        out += [c_array(f"VC_W{i}", p[f"W{i}"]), c_array(f"VC_B{i}", p[f"b{i}"])]
    out += [c_array("VC_WD", p["Wd"]), c_array("VC_BD", p["bd"]),
            "static const char *const VC_LABELS[VC_N_OUT] = {" + ", ".join(f'"{l}"' for l in model_labels) + "};",
            "static const char *const VC_SAY[VC_N_OUT] = {" + ", ".join(f'"{esc(say[l])}"' for l in model_labels) + "};",
            "// index into vocabulary.csv (= VOICE_CLIPS in voice_clips.h)",
            "static const int VC_VOCAB_INDEX[VC_N_OUT] = {" + ", ".join(str(vocab_labels.index(l)) for l in model_labels) + "};",
            ""]
    with open(MODEL_H, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    os.makedirs(os.path.dirname(NPZ), exist_ok=True)
    np.savez(NPZ, mean=mean, std=std, labels=np.array(model_labels),
             say=np.array([say[l] for l in model_labels]), info=np.array(info), **p)
    print("wrote", os.path.relpath(MODEL_H, ROOT), "and", os.path.relpath(NPZ, ROOT))


def export_vectors(takes, p, mean, std, n=6, seed=1):
    rng = np.random.default_rng(seed)
    picks = rng.choice(len(takes), size=min(n, len(takes)), replace=False)
    X = []
    for i in picks:
        fr = takes[i][3]
        s = int(rng.integers(0, len(fr) - vc.SEQ_LEN + 1))
        X.append(fr[s:s + vc.SEQ_LEN])
    X = np.array(X)
    probs = vc.predict_proba(p, mean, std, X)
    out = ["// AUTO-GENERATED by ml/train_cnn.py — PC parity test data (NumPy vs firmware C++).",
           "#pragma once", f"#define TVC_N {len(X)}",
           c_array("TVC_FRAMES", X), c_array("TVC_PROBS", probs),
           c_array("TVC_BEST", probs.argmax(axis=1), "int"), ""]
    with open(VECTORS_H, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("wrote", os.path.relpath(VECTORS_H, ROOT))


def save_report(res, model_labels, info, split_name, n_takes, users, y, pred):
    os.makedirs(REPORTS, exist_ok=True)
    cm = confusion_matrix(y, pred, labels=range(len(model_labels)))
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        fig, ax = plt.subplots(figsize=(9, 8))
        norm = cm / np.maximum(cm.sum(axis=1, keepdims=True), 1)
        ax.imshow(norm, cmap="Blues", vmin=0, vmax=1)
        ax.set_xticks(range(len(model_labels)), model_labels, rotation=90, fontsize=8)
        ax.set_yticks(range(len(model_labels)), model_labels, fontsize=8)
        ax.set_xlabel("predicted")
        ax.set_ylabel("true")
        ax.set_title(f"CNN confusion ({split_name}) — accuracy {accuracy_score(y, pred):.1%}")
        for i in range(len(model_labels)):
            for j in range(len(model_labels)):
                if cm[i, j]:
                    ax.text(j, i, cm[i, j], ha="center", va="center", fontsize=6,
                            color="white" if norm[i, j] > 0.5 else "black")
        fig.tight_layout()
        fig.savefig(os.path.join(REPORTS, "cnn_confusion.png"), dpi=130)
        plt.close(fig)
    except ImportError:
        pass
    text = classification_report(y, pred, labels=range(len(model_labels)), target_names=model_labels,
                                 digits=3, zero_division=0)
    rows = "\n".join(f"| {name} | {a:.1%} | {b:.1%} |" for name, (a, b) in res.items())
    with open(os.path.join(REPORTS, "cnn_report.md"), "w", encoding="utf-8") as f:
        f.write(f"# Gesture model report — CNN (v2) vs MLP (v1)\n\n{info}\n\n"
                f"- Cross-validation: {split_name} (a take/user is never in both train and test)\n"
                f"- Takes: {n_takes} · users: {', '.join(sorted(set(users)))}\n"
                f"- 'Drifted' = test windows with flex gain −8…−18 %, offset +0.04…+0.10 and a 10° IMU tilt "
                f"(glove re-worn without recalibrating)\n\n"
                f"| Model | Clean windows | Drifted windows |\n|---|---|---|\n{rows}\n\n"
                f"![confusion](cnn_confusion.png)\n\nCNN, clean windows:\n```\n{text}```\n")
    print(f"report -> {os.path.relpath(os.path.join(REPORTS, 'cnn_report.md'), ROOT)}")


# ----------------------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--synthetic", action="store_true")
    ap.add_argument("--data", default=None)
    ap.add_argument("--epochs", type=int, default=40)
    ap.add_argument("--folds", type=int, default=5, help="0 = no cross-validation")
    ap.add_argument("--by-user", action="store_true")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--hands", type=int, choices=(1, 2), default=None,
                    help="1 = right glove only, 2 = both gloves (default: whatever the data has)")
    args = ap.parse_args()

    data_dir = args.data or os.path.join(HERE, "data_synthetic" if args.synthetic else "data")
    vocab = load_vocab()
    takes = [t for t in load_takes(data_dir, [v[0] for v in vocab]) if len(t[3]) >= vc.SEQ_LEN]
    if not takes:
        sys.exit(f"no recordings of >= {vc.SEQ_LEN} frames in {data_dir}")
    # one-glove takes (15 ch) and two-glove takes (30 ch, + left_ok) can be mixed: pad the left glove with zeros
    n_ch = 15 * (args.hands or (2 if any(t[3].shape[1] >= 30 for t in takes) else 1))
    takes = [(l, u, pth, np.pad(f[:, :n_ch], ((0, 0), (0, max(0, n_ch - f.shape[1]))))) for l, u, pth, f in takes]
    print(f"input: {n_ch} channels ({'two gloves' if n_ch == 30 else 'right glove only'})")
    model_labels = [v[0] for v in vocab if any(t[0] == v[0] for t in takes)]
    if len(model_labels) < 3:
        sys.exit("need at least 3 labels with data")
    li = {l: i for i, l in enumerate(model_labels)}
    y_take = np.array([li[t[0]] for t in takes])
    users = np.array([t[1] for t in takes])
    n_out = len(model_labels)
    placeholder = args.synthetic or "synthetic" in data_dir
    stamp = datetime.date.today().isoformat()
    print(f"{len(takes)} takes, {n_out} classes, users: {', '.join(sorted(set(users)))}")

    cv_acc = None
    if args.folds:
        groups = users if args.by_user else np.arange(len(takes))
        split_name = "leave-one-user-out" if args.by_user else f"grouped {args.folds}-fold by take"
        n_splits = min(args.folds, len(set(groups)))
        Y, P_cnn, P_mlp, P_cnn_d, P_mlp_d = [], [], [], [], []
        rng = np.random.default_rng(123)
        for fold, (tr, te) in enumerate(GroupKFold(n_splits=n_splits).split(np.zeros(len(takes)), y_take, groups)):
            t0 = time.time()
            p, mean, std = train_cnn([takes[i] for i in tr], y_take[tr], n_out, args.epochs, args.seed + fold)
            tr_w = eval_windows(takes, tr, li)
            mlp, mm, ms = fit_mlp(tr_w[1], tr_w[2], 32)                    # v1 model, as in train.py
            X, F, y, _g = eval_windows(takes, te, li)
            Xd = vc.drift(X, rng)
            Fd = np.stack([compute_features(w[-25:]) for w in Xd])
            Y.append(y)
            P_cnn.append(vc.predict_proba(p, mean, std, X).argmax(1))
            P_cnn_d.append(vc.predict_proba(p, mean, std, Xd).argmax(1))
            P_mlp.append(mlp.predict((F - mm) / ms))
            P_mlp_d.append(mlp.predict((Fd - mm) / ms))
            print(f"fold {fold+1}/{n_splits}: CNN {accuracy_score(y, P_cnn[-1]):.1%} · MLP {accuracy_score(y, P_mlp[-1]):.1%}"
                  f"  (drifted: CNN {accuracy_score(y, P_cnn_d[-1]):.1%} · MLP {accuracy_score(y, P_mlp_d[-1]):.1%})"
                  f"  [{time.time()-t0:.0f} s]")
        Y = np.concatenate(Y)
        res = {"CNN v2 (1.0 s, raw signal)": (accuracy_score(Y, np.concatenate(P_cnn)), accuracy_score(Y, np.concatenate(P_cnn_d))),
               "MLP v1 (0.5 s, 16 features)": (accuracy_score(Y, np.concatenate(P_mlp)), accuracy_score(Y, np.concatenate(P_mlp_d)))}
        cv_acc = res["CNN v2 (1.0 s, raw signal)"][0]
        info = (f"{'SYNTHETIC ' if placeholder else ''}data {os.path.relpath(data_dir, ROOT)} · {len(takes)} takes · "
                f"{n_out} classes · CNN CV acc {cv_acc:.1%} · {stamp}")
        save_report(res, model_labels, info, split_name, len(takes), users, Y, np.concatenate(P_cnn))
        for k, (a, b) in res.items():
            print(f"  {k:30s} clean {a:.1%}   drifted {b:.1%}")

    print("training final model on all takes ...")
    p, mean, std = train_cnn(takes, y_take, n_out, args.epochs, args.seed, verbose=True)
    info = (f"{'SYNTHETIC ' if placeholder else ''}data {os.path.relpath(data_dir, ROOT)} · {len(takes)} takes · "
            f"{n_out} classes · CNN CV acc {'n/a' if cv_acc is None else f'{cv_acc:.1%}'} · {stamp}")
    export(p, mean, std, model_labels, vocab, info, placeholder)
    export_vectors(takes, p, mean, std)


if __name__ == "__main__":
    main()
