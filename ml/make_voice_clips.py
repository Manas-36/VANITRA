"""Build firmware/glove_unit/voice_clips.h — the words the glove speaks, embedded in flash.

    python ml/make_voice_clips.py                    # robot voice from espeak-ng (offline TTS)
    python ml/make_voice_clips.py --wav-dir my_wavs  # your own recordings: my_wavs/<LABEL>.wav

Own recordings sound far better (record a teammate saying each phrase, any rate/bit depth —
they are converted to 16 kHz 16-bit mono, trimmed and normalised). Needs ffmpeg OR espeak-ng.
Order follows ml/vocabulary.csv; labels with an empty `say` (REST) get no clip.
"""
import argparse
import csv
import io
import os
import shutil
import subprocess
import sys
import tempfile
import wave

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT_H = os.path.join(ROOT, "firmware", "glove_unit", "voice_clips.h")
RATE = 16000


def load_vocab():
    with open(os.path.join(HERE, "vocabulary.csv"), newline="", encoding="utf-8") as f:
        return [(r["label"], r["say"]) for r in csv.DictReader(f)]


def read_wav_any(path):
    """Returns float mono samples at RATE. Uses ffmpeg for anything that is not 16k mono 16-bit."""
    try:
        with wave.open(path, "rb") as w:
            if w.getframerate() == RATE and w.getnchannels() == 1 and w.getsampwidth() == 2:
                return np.frombuffer(w.readframes(w.getnframes()), dtype="<i2").astype(np.float32) / 32768
    except wave.Error:
        pass
    if not shutil.which("ffmpeg"):
        sys.exit(f"{path}: convert to 16 kHz mono 16-bit WAV, or install ffmpeg")
    raw = subprocess.run(["ffmpeg", "-loglevel", "error", "-i", path, "-ac", "1", "-ar", str(RATE),
                          "-f", "s16le", "-"], check=True, capture_output=True).stdout
    return np.frombuffer(raw, dtype="<i2").astype(np.float32) / 32768


def tts(text, voice, speed):
    exe = shutil.which("espeak-ng") or shutil.which("espeak")
    if not exe:
        sys.exit("install espeak-ng (sudo apt install espeak-ng / https://github.com/espeak-ng/espeak-ng) "
                 "or pass --wav-dir with your own recordings")
    with tempfile.TemporaryDirectory() as d:
        p = os.path.join(d, "x.wav")
        subprocess.run([exe, "-v", voice, "-s", str(speed), "-w", p, text], check=True)
        return read_wav_any(p)


def clean(x, gain_db=-1.0):
    """Trim silence, short fades, normalise to gain_db dBFS."""
    thr = 0.02 * (np.abs(x).max() or 1)
    idx = np.where(np.abs(x) > thr)[0]
    if len(idx):
        x = x[max(idx[0] - 400, 0): idx[-1] + 800]
    fade = min(160, len(x) // 4)
    if fade:
        ramp = np.linspace(0, 1, fade)
        x[:fade] *= ramp
        x[-fade:] *= ramp[::-1]
    peak = np.abs(x).max() or 1
    return x / peak * (10 ** (gain_db / 20))


def to_wav_bytes(x):
    buf = io.BytesIO()
    with wave.open(buf, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes((np.clip(x, -1, 1) * 32767).astype("<i2").tobytes())
    return buf.getvalue()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--wav-dir", help="folder with <LABEL>.wav recordings (missing ones fall back to TTS)")
    ap.add_argument("--voice", default="en-us+f3", help="espeak-ng voice, e.g. en-us+f3, en+m3, hi")
    ap.add_argument("--speed", type=int, default=150, help="espeak-ng words per minute")
    args = ap.parse_args()

    vocab = load_vocab()
    parts = ["// AUTO-GENERATED by ml/make_voice_clips.py — 16 kHz 16-bit mono WAV clips in flash.",
             f"// source: {'recordings in ' + args.wav_dir + ' + ' if args.wav_dir else ''}espeak-ng voice {args.voice}",
             "#pragma once", "#include <stdint.h>", f"#define VOICE_SAMPLE_RATE {RATE}",
             f"#define VOICE_N {len(vocab)}",
             "struct VoiceClip { const uint8_t *data; uint32_t len; };"]
    entries, total = [], 0
    for i, (label, say) in enumerate(vocab):
        if not say:
            entries.append(f"  {{nullptr, 0}},  // {label} (silent)")
            continue
        own = os.path.join(args.wav_dir, f"{label}.wav") if args.wav_dir else None
        x = read_wav_any(own) if own and os.path.exists(own) else tts(say, args.voice, args.speed)
        data = to_wav_bytes(clean(x.copy()))
        total += len(data)
        hexes = [f"0x{b:02x}" for b in data]
        body = ",\n  ".join(",".join(hexes[k:k + 24]) for k in range(0, len(hexes), 24))
        parts.append(f"// {label}: \"{say}\" ({len(data) / 2 / RATE:.2f} s)\n"
                     f"static const uint8_t VOICE_{i}[{len(data)}] = {{\n  {body}\n}};")
        entries.append(f"  {{VOICE_{i}, sizeof(VOICE_{i})}},  // {label}")
        print(f"{label:12s} {len(data) / 2 / RATE:5.2f} s  \"{say}\"")
    parts.append("static const VoiceClip VOICE_CLIPS[VOICE_N] = {\n" + "\n".join(entries) + "\n};\n")
    with open(OUT_H, "w", encoding="utf-8") as f:
        f.write("\n".join(parts))
    print(f"wrote {os.path.relpath(OUT_H, ROOT)} — {total / 1024:.0f} KB of audio")


if __name__ == "__main__":
    main()
