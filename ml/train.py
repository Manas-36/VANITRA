"""Train the glove gesture classifier and export it to the firmware.

    python ml/train.py                 # real data from ml/data/
    python ml/train.py --synthetic     # pipeline test with ml/data_synthetic/ (make_synthetic_data.py)

Writes
    firmware/glove_unit/model.h          weights + labels for the ESP32-S3 (no TFLite needed)
    firmware/tests/host/test_vectors.h   frames + expected outputs for the PC parity test
    ml/reports/report.md, confusion.png  cross-validated accuracy, grouped by take (or by user)
"""
import argparse
import csv
import datetime
import glob
import os
import sys

import numpy as np
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix
from sklearn.model_selection import GroupKFold
from sklearn.neural_network import MLPClassifier

from vanitra_features import FEATURE_NAMES, N_FEAT, WIN, compute_features, windows_from_recording

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
MODEL_H = os.path.join(ROOT, "firmware", "glove_unit", "model.h")
VECTORS_H = os.path.join(ROOT, "firmware", "tests", "host", "test_vectors.h")
REPORTS = os.path.join(HERE, "reports")


def load_vocab():
    with open(os.path.join(HERE, "vocabulary.csv"), newline="", encoding="utf-8") as f:
        return [(r["label"], r["say"]) for r in csv.DictReader(f)]


def load_takes(data_dir, labels):
    """Returns list of (label, user, path, frames[N,15])."""
    takes = []
    for label in labels:
        for path in sorted(glob.glob(os.path.join(data_dir, label, "*.csv"))):
            arr = np.loadtxt(path, delimiter=",", skiprows=1, ndmin=2)
            if len(arr) < WIN:
                continue
            user = os.path.basename(path).split("_")[0]
            takes.append((label, user, path, arr[:, 1:]))      # drop t_ms
    return takes


def build_dataset(takes, label_index):
    X, y, groups_take, groups_user = [], [], [], []
    for t_id, (label, user, _path, frames) in enumerate(takes):
        for f in windows_from_recording(frames):
            X.append(f)
            y.append(label_index[label])
            groups_take.append(t_id)
            groups_user.append(user)
    return np.array(X), np.array(y), np.array(groups_take), np.array(groups_user)


def fit(X, y, hidden, seed=0):
    mean = X.mean(axis=0)
    std = X.std(axis=0)
    std[std < 1e-6] = 1.0
    clf = MLPClassifier(hidden_layer_sizes=(hidden,), activation="relu", alpha=1e-3,
                        max_iter=1500, random_state=seed)
    clf.fit((X - mean) / std, y)
    return clf, mean, std


def predict_proba(clf, mean, std, X):
    return clf.predict_proba((X - mean) / std)


def c_array(name, values, ctype="float", per_line=8):
    def fmt(v):
        t = f"{float(v):.8g}"
        return (t if any(ch in t for ch in ".e") else t + ".0") + "f"
    vals = [fmt(v) if ctype == "float" else str(int(v)) for v in np.asarray(values).ravel()]
    lines = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    return f"static const {ctype} {name}[{len(vals)}] = {{\n  " + ",\n  ".join(lines) + "\n};\n"


def export_model(clf, mean, std, model_labels, vocab, info, placeholder):
    vocab_labels = [v[0] for v in vocab]
    say = dict(vocab)
    w1, w2 = clf.coefs_
    b1, b2 = clf.intercepts_
    n_in, n_hid = w1.shape
    n_out = w2.shape[1]
    rest = model_labels.index("REST") if "REST" in model_labels else -1
    esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
    out = [
        "// AUTO-GENERATED by ml/train.py — do not edit by hand.",
        f"// {info}",
    ]
    if placeholder:
        out += ["// *** PLACEHOLDER MODEL: trained on SYNTHETIC data (ml/make_synthetic_data.py). ***",
                "// *** It only proves the pipeline. Record real takes and run: python ml/train.py ***"]
    out += [
        "#pragma once",
        f"#define VM_N_IN {n_in}",
        f"#define VM_N_HID {n_hid}",
        f"#define VM_N_OUT {n_out}",
        f"#define VM_REST_INDEX {rest}",
        f'#define VM_INFO "{esc(info)}"',
        f"#define VM_PLACEHOLDER {1 if placeholder else 0}",
        "// feature order: " + ", ".join(FEATURE_NAMES),
        c_array("VM_MEAN", mean),
        c_array("VM_STD", std),
        c_array("VM_W1", w1),          # [in][hid] row-major
        c_array("VM_B1", b1),
        c_array("VM_W2", w2),          # [hid][out] row-major
        c_array("VM_B2", b2),
        "static const char *const VM_LABELS[VM_N_OUT] = {" + ", ".join(f'"{l}"' for l in model_labels) + "};",
        "static const char *const VM_SAY[VM_N_OUT] = {" + ", ".join(f'"{esc(say[l])}"' for l in model_labels) + "};",
        "// index into vocabulary.csv (= VOICE_CLIPS in voice_clips.h)",
        "static const int VM_VOCAB_INDEX[VM_N_OUT] = {" + ", ".join(str(vocab_labels.index(l)) for l in model_labels) + "};",
        "",
    ]
    with open(MODEL_H, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("wrote", os.path.relpath(MODEL_H, ROOT))


def export_test_vectors(takes, clf, mean, std, n=6, seed=1):
    rng = np.random.default_rng(seed)
    picks = rng.choice(len(takes), size=min(n, len(takes)), replace=False)
    frames_all, feats_all, probs_all, best_all = [], [], [], []
    for i in picks:
        frames = takes[i][3]
        start = int(rng.integers(0, len(frames) - WIN + 1))
        win = frames[start:start + WIN]
        f = compute_features(win)
        p = predict_proba(clf, mean, std, f[None, :])[0]
        frames_all.append(win)
        feats_all.append(f)
        probs_all.append(p)
        best_all.append(int(np.argmax(p)))
    k = len(picks)
    out = ["// AUTO-GENERATED by ml/train.py — PC parity test data (Python vs firmware C++).",
           "#pragma once",
           f"#define TV_N {k}",
           c_array("TV_FRAMES", np.array(frames_all)),          # [k][WIN][15]
           c_array("TV_FEATURES", np.array(feats_all)),        # [k][N_FEAT]
           c_array("TV_PROBS", np.array(probs_all)),           # [k][N_OUT]
           c_array("TV_BEST", np.array(best_all), "int"), ""]
    os.makedirs(os.path.dirname(VECTORS_H), exist_ok=True)
    with open(VECTORS_H, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("wrote", os.path.relpath(VECTORS_H, ROOT))


def save_report(y, pred, model_labels, info, split_name, n_takes, users):
    os.makedirs(REPORTS, exist_ok=True)
    acc = accuracy_score(y, pred)
    cm = confusion_matrix(y, pred, labels=range(len(model_labels)))
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        fig, ax = plt.subplots(figsize=(9, 8))
        norm = cm / np.maximum(cm.sum(axis=1, keepdims=True), 1)
        ax.imshow(norm, cmap="Blues", vmin=0, vmax=1)
        ax.set_xticks(range(len(model_labels)), model_labels, rotation=90, fontsize=8)
        ax.set_yticks(range(len(model_labels)), model_labels, fontsize=8)
        ax.set_xlabel("predicted")
        ax.set_ylabel("true")
        ax.set_title(f"Gesture confusion ({split_name}) — accuracy {acc:.1%}")
        for i in range(len(model_labels)):
            for j in range(len(model_labels)):
                if cm[i, j]:
                    ax.text(j, i, cm[i, j], ha="center", va="center", fontsize=6,
                            color="white" if norm[i, j] > 0.5 else "black")
        fig.tight_layout()
        fig.savefig(os.path.join(REPORTS, "confusion.png"), dpi=130)
        plt.close(fig)
    except ImportError:
        pass
    text = classification_report(y, pred, labels=range(len(model_labels)), target_names=model_labels,
                                 digits=3, zero_division=0)
    with open(os.path.join(REPORTS, "report.md"), "w", encoding="utf-8") as f:
        f.write(f"# Gesture model report\n\n{info}\n\n"
                f"- Cross-validation: {split_name} (a take/user is never in both train and test)\n"
                f"- Takes: {n_takes} · users: {', '.join(sorted(set(users)))}\n"
                f"- Window accuracy: **{acc:.1%}** over {len(y)} windows of {WIN} frames\n\n"
                f"![confusion](confusion.png)\n\n```\n{text}```\n")
    print(f"cross-validated window accuracy: {acc:.1%} ({split_name})")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--synthetic", action="store_true", help="use ml/data_synthetic (pipeline test)")
    ap.add_argument("--data", default=None)
    ap.add_argument("--hidden", type=int, default=32)
    ap.add_argument("--by-user", action="store_true", help="leave-one-user-out instead of by take")
    args = ap.parse_args()

    data_dir = args.data or os.path.join(HERE, "data_synthetic" if args.synthetic else "data")
    vocab = load_vocab()
    takes = load_takes(data_dir, [v[0] for v in vocab])
    if not takes:
        sys.exit(f"no recordings in {data_dir} — run collect_data.py (or make_synthetic_data.py + --synthetic)")
    model_labels = [v[0] for v in vocab if any(t[0] == v[0] for t in takes)]
    missing = [v[0] for v in vocab if v[0] not in model_labels]
    if missing:
        print("warning: no takes for", ", ".join(missing), "- they will not be recognised")
    if len(model_labels) < 3:
        sys.exit("need at least 3 labels with data")
    label_index = {l: i for i, l in enumerate(model_labels)}

    X, y, g_take, g_user = build_dataset(takes, label_index)
    groups, split_name = (g_user, "leave-one-user-out") if args.by_user else (g_take, "grouped 5-fold by take")
    n_splits = min(5, len(set(groups)))
    pred = np.zeros_like(y)
    for tr, te in GroupKFold(n_splits=n_splits).split(X, y, groups):
        clf, mean, std = fit(X[tr], y[tr], args.hidden)
        pred[te] = clf.predict((X[te] - mean) / std)

    placeholder = args.synthetic or "synthetic" in data_dir
    stamp = datetime.date.today().isoformat()
    acc = accuracy_score(y, pred)
    info = (f"{'SYNTHETIC ' if placeholder else ''}data {os.path.relpath(data_dir, ROOT)} · {len(takes)} takes · "
            f"{len(model_labels)} classes · CV acc {acc:.1%} · {stamp}")
    save_report(y, pred, model_labels, info, split_name, len(takes), g_user)

    clf, mean, std = fit(X, y, args.hidden)
    export_model(clf, mean, std, model_labels, vocab, info, placeholder)
    export_test_vectors(takes, clf, mean, std)
    assert X.shape[1] == N_FEAT


if __name__ == "__main__":
    main()
