"""Build firmware/wristband_unit/commands.h from firmware/wristband_unit/phrases.csv.

ESP-SR MultiNet (English, on the ESP32-S3) recognises a fixed list of up to 200 phrases offline.
Each phrase needs a phoneme string; this script makes them with g2p_en and Espressif's
phoneme alphabet (same mapping as esp-sr/tool/multinet_g2p.py).

    pip install g2p_en nltk inflect --no-deps g2p_en   (see docs/setup.md if pip complains)
    python tools/make_sr_commands.py

Edit phrases.csv (alternatives separated by |), rerun, re-flash the wristband.
"""
import csv
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "firmware", "wristband_unit", "phrases.csv")
OUT = os.path.join(ROOT, "firmware", "wristband_unit", "commands.h")

# Espressif MultiNet5 English phoneme alphabet (from esp-sr/tool/multinet_g2p.py, MIT licence)
ALPHABET = {"AE1": "a", "N": "N", " ": " ", "OW1": "b", "V": "V", "AH0": "c", "L": "L", "F": "F", "EY1": "d",
            "S": "S", "B": "B", "R": "R", "AO1": "e", "D": "D", "AH1": "c", "EH1": "f", "OW0": "b", "IH0": "g",
            "G": "G", "HH": "h", "K": "K", "IH1": "g", "W": "W", "AY1": "i", "T": "T", "M": "M", "Z": "Z",
            "DH": "j", "ER0": "k", "P": "P", "NG": "l", "IY1": "m", "AA1": "n", "Y": "Y", "UW1": "o", "IY0": "m",
            "EH2": "f", "CH": "p", "AE0": "a", "JH": "q", "ZH": "r", "AA2": "n", "SH": "s", "AW1": "t",
            "OY1": "u", "AW2": "t", "IH2": "g", "AE2": "a", "EY2": "d", "ER1": "k", "TH": "v", "UH1": "w",
            "UW2": "o", "OW2": "b", "AY2": "i", "UW0": "o", "AH2": "c", "EH0": "f", "AW0": "t", "AO2": "e",
            "AO0": "e", "UH0": "w", "UH2": "w", "AA0": "n", "AY0": "i", "IY2": "m", "EY0": "d", "ER2": "k",
            "OY2": "u", "OY0": "u"}


def main():
    try:
        from g2p_en import G2p
    except ImportError:
        sys.exit("pip install g2p_en (see docs/setup.md)")
    g2p = G2p()
    with open(SRC, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    enum, cmds, info = [], [], []
    for cid, r in enumerate(rows):
        enum.append(f"  CMD_{r['name']} = {cid},")
        info.append(f'  {{"{r["name"]}", "{r["morse"]}", "{r["display"]}"}},')
        for phrase in r["phrases"].split("|"):
            phrase = phrase.strip()
            clean = re.sub(r"[^a-zA-Z ]", "", phrase).lower()
            ph = "".join(ALPHABET.get(p, "") for p in g2p(clean)).strip()
            if len(phrase) >= 64 or len(ph) >= 64:
                sys.exit(f"phrase too long for ESP-SR (63 chars max): {phrase}")
            cmds.append(f'  {{{cid}, "{phrase}", "{ph}"}},')
    if len(cmds) > 200:
        sys.exit("ESP-SR MultiNet supports at most 200 phrases")

    out = ["// AUTO-GENERATED by tools/make_sr_commands.py from phrases.csv — do not edit by hand.",
           "#pragma once",
           '#include "ESP_SR.h"',
           "enum {", *enum, f"  CMD_COUNT = {len(rows)}", "};",
           "// {command id, phrase, ESP-SR phonemes}",
           "static const sr_cmd_t SR_COMMANDS[] = {", *cmds, "};",
           "#define SR_COMMANDS_LEN (sizeof(SR_COMMANDS) / sizeof(SR_COMMANDS[0]))",
           "struct PhraseInfo { const char *name; const char *morse; const char *display; };",
           "// morse: what the wristband vibrates (short code). '*ALERT' = special danger pattern.",
           "static const PhraseInfo PHRASES[CMD_COUNT] = {", *info, "};", ""]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(rows)} meanings, {len(cmds)} phrases")


if __name__ == "__main__":
    main()
